#[tauri::command]
pub fn vault_read_base64(
    app: AppHandle,
    user: String,
    project: String,
    doc_id: String,
    ext: String,
    variant: String,
) -> Result<Option<String>, String> {
    let path = document_path(&app, &user, &project, &doc_id, &ext, &variant)?;
    let meta = match fs::metadata(&path) {
        Ok(meta) => meta,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(error.to_string()),
    };
    if meta.len() > MAX_INLINE_BYTES {
        return Err("This file is too large to preview here. Open it with its own app.".into());
    }
    let bytes = fs::read(&path).map_err(|e| e.to_string())?;
    Ok(Some(encode_base64(&bytes)))
}

