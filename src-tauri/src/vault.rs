#[cfg(test)]
mod tests {
    use super::{
        checked_doc_id, checked_ext, checksum_of, decode_base64, encode_base64, file_checksum,
        open_allowed, sanitize_export_name, unique_export_path,
    };
    use std::fs;
    use std::path::PathBuf;

    #[test]
    fn document_ids_cannot_escape_the_folder() {
        assert!(checked_doc_id("doc-m8x1-9f3a").is_ok());
        assert!(checked_doc_id("../../etc/passwd").is_err());
        assert!(checked_doc_id("doc id").is_err());
        assert!(checked_doc_id("short").is_err());
    }

    #[test]
    fn extensions_are_narrowed_to_a_safe_token() {
        assert_eq!(checked_ext(".PDF").unwrap(), "pdf");
        assert_eq!(checked_ext("").unwrap(), "bin");
        assert!(checked_ext("a/b").is_err());
        assert!(checked_ext("sh;rm").is_err());
    }

    #[test]
    fn base64_round_trips_arbitrary_bytes() {
        let bytes: Vec<u8> = (0..=255u8).cycle().take(5000).collect();
        let encoded = encode_base64(&bytes);
        assert_eq!(decode_base64(&encoded).unwrap(), bytes);
        assert_eq!(encode_base64(b"a"), "YQ==");
        assert_eq!(encode_base64(b"ab"), "YWI=");
        assert_eq!(encode_base64(b"abc"), "YWJj");
        assert!(decode_base64("!!!").is_err());
    }

    #[test]
    fn checksum_is_stable_and_size_aware() {
        assert_eq!(checksum_of(b"stambha"), checksum_of(b"stambha"));
        assert_ne!(checksum_of(b"stambha"), checksum_of(b"sthamb"));
    }

    #[test]
    fn only_safe_extensions_may_be_opened() {
        for ext in ["pdf", "dwg", "docx", "png", "xlsx"] {
            assert!(open_allowed(ext), "{ext} should be openable");
        }
        for ext in ["exe", "app", "command", "sh", "bat", "pkg", "dmg", "js"] {
            assert!(!open_allowed(ext), "{ext} must never be launched");
        }
    }

    #[test]
    fn export_names_never_overwrite_a_previous_copy() {
        let dir: PathBuf =
            std::env::temp_dir().join(format!("cos-vault-export-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        let first = unique_export_path(&dir, "site plan.dwg");
        assert_eq!(first.file_name().unwrap(), "site plan.dwg");
        fs::write(&first, b"x").unwrap();
        let second = unique_export_path(&dir, "site plan.dwg");
        assert_eq!(second.file_name().unwrap(), "site plan (2).dwg");
        fs::write(&second, b"x").unwrap();
        let third = unique_export_path(&dir, "site plan.dwg");
        assert_eq!(third.file_name().unwrap(), "site plan (3).dwg");
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn export_names_strip_paths_and_control_characters() {
        let safe = sanitize_export_name("../../etc/passwd");
        assert!(!safe.contains('/'));
        assert!(!safe.starts_with('.'));
        assert!(!safe.starts_with('-'));
        assert_eq!(safe, "file-..-..-etc-passwd");
        assert_eq!(sanitize_export_name("  ..  "), "document");
        assert!(!sanitize_export_name("a\u{0}b").contains('\u{0}'));
    }

    #[test]
    fn export_names_avoid_windows_device_names() {
        assert_eq!(sanitize_export_name("CON.pdf"), "file-CON.pdf");
        assert_eq!(sanitize_export_name("nul"), "file-nul");
        assert_eq!(sanitize_export_name("COM1.dwg"), "file-COM1.dwg");
        // Ordinary names, including near-misses, are untouched.
        assert_eq!(sanitize_export_name("console.pdf"), "console.pdf");
        assert_eq!(sanitize_export_name("COM10.pdf"), "COM10.pdf");
    }

    #[test]
    fn streaming_checksum_matches_the_in_memory_one() {
        let dir: PathBuf =
            std::env::temp_dir().join(format!("cos-vault-hash-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        let path = dir.join("sample.bin");
        let bytes: Vec<u8> = (0..=255u8).cycle().take(200_000).collect();
        fs::write(&path, &bytes).unwrap();
        let (size, hash) = file_checksum(&path).unwrap();
        assert_eq!(size as usize, bytes.len());
        assert_eq!(hash, checksum_of(&bytes));
        let _ = fs::remove_dir_all(&dir);
    }
}
