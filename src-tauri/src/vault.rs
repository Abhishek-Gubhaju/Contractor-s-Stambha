#[tauri::command]
pub fn vault_reveal_folder(app: AppHandle, user: String, project: String) -> Result<(), String> {
    // A folder is opened as a folder. `reveal_path` selects a *file* inside its
    // parent (Explorer's `/select,`), which a trailing `.` cannot do on Windows.
    let dir = vault_dir(&app, &user, &project)?;
    crate::open_dir(&dir)
}

fn sanitize_export_name(value: &str) -> String {
    let mut clean = String::new();
    for ch in value.chars() {
        if clean.len() >= 120 {
            break;
        }
        if ch.is_control() || matches!(ch, '/' | '\\' | ':' | '*' | '?' | '"' | '<' | '>' | '|') {
            clean.push('-');
        } else {
            clean.push(ch);
        }
    }
    // A leading dot would hide the export on Unix, and a leading dash makes it
    // look like a command-line flag. Neither is a useful file name, so prefix
    // it instead of dropping the person's words.
    let trimmed = clean.trim().trim_end_matches([' ', '.']).trim();
    if trimmed.is_empty() {
        return "document".to_string();
    }
    if trimmed.starts_with('.') || trimmed.starts_with('-') {
        return format!("file-{trimmed}");
    }
    // Windows cannot create a file called `CON`, `NUL`, `COM1`… at all, so an
    // export whose name is a device name gets the same safe prefix.
    if crate::is_reserved_windows_name(trimmed) {
        return format!("file-{trimmed}");
    }
    trimmed.to_string()
}

fn unique_export_path(dir: &Path, file_name: &str) -> PathBuf {
    let safe = sanitize_export_name(file_name);
    let first = dir.join(&safe);
    if !first.exists() {
        return first;
    }
    let path = Path::new(&safe);
    let stem = path
        .file_stem()
        .and_then(|value| value.to_str())
        .unwrap_or("document");
    let ext = path.extension().and_then(|value| value.to_str()).unwrap_or("");
    for n in 2..10_000 {
        let name = if ext.is_empty() {
            format!("{stem} ({n})")
        } else {
            format!("{stem} ({n}).{ext}")
        };
        let candidate = dir.join(name);
        if !candidate.exists() {
            return candidate;
        }
    }
    dir.join(format!("{stem}-copy.{ext}"))
}

#[tauri::command]
pub fn vault_export_copy(
    app: AppHandle,
    user: String,
    project: String,
    doc_id: String,
    ext: String,
    file_name: String,
) -> Result<String, String> {
    let source = document_path(&app, &user, &project, &doc_id, &ext, "file")?;
    if !source.is_file() {
        return Err("That file is missing from this computer.".into());
    }
    let downloads = downloads_dir(&app)?;
    let dir = downloads
        .join(crate::APP_NAME)
        .join(checked_vault_segment(&user, "account")?);
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let target = unique_export_path(&dir, &file_name);
    fs::copy(&source, &target).map_err(|e| e.to_string())?;
    Ok(target.to_string_lossy().to_string())
}

