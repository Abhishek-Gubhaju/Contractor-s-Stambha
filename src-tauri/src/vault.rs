/// A document id is generated by the app: `doc-<base36 time>-<random>`.
pub(crate) fn checked_doc_id(value: &str) -> Result<&str, String> {
    let ok = (6..=64).contains(&value.len())
        && value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if ok {
        Ok(value)
    } else {
        Err(format!("refusing unsafe document id: {value}"))
    }
}

/// User and project ids are allowed dots (job numbers sometimes carry them),
/// but never a separator or a bare `.`/`..`.
fn checked_vault_segment<'a>(value: &'a str, label: &str) -> Result<&'a str, String> {
    let trimmed = value.trim();
    // A single folder name may contain spaces and dots (job codes sometimes
    // do), but never a separator, a control character, or `.`/`..`.
    let ok = !trimmed.is_empty()
        && trimmed.len() <= 80
        && trimmed != "."
        && trimmed != ".."
        && !trimmed
            .chars()
            .any(|c| c == '/' || c == '\\' || c.is_control());
    if ok {
        Ok(trimmed)
    } else {
        Err(format!("refusing unsafe {label} name: {value}"))
    }
}

fn checked_ext(value: &str) -> Result<String, String> {
    let clean = value
        .trim()
        .trim_start_matches('.')
        .to_ascii_lowercase();
    if clean.is_empty() {
        return Ok("bin".to_string());
    }
    let ok = clean.len() <= 16 && clean.chars().all(|c| c.is_ascii_alphanumeric());
    if ok {
        Ok(clean)
    } else {
        Err(format!("refusing unsafe file extension: {value}"))
    }
}

pub(crate) fn open_allowed(ext: &str) -> bool {
    OPEN_EXTS.contains(&ext.to_ascii_lowercase().as_str())
}

fn variant_suffix(variant: &str) -> Result<&'static str, String> {
    match variant {
        "file" => Ok("part"),
        "thumb" => Ok("thumb.part"),
        _ => Err(format!("unknown file variant: {variant}")),
    }
}

fn file_name(doc_id: &str, ext: &str, variant: &str) -> Result<String, String> {
    let id = checked_doc_id(doc_id)?;
    match variant {
        "thumb" => Ok(format!("{id}.thumb.jpg")),
        "file" => Ok(format!("{id}.{}", checked_ext(ext)?)),
        _ => Err(format!("unknown file variant: {variant}")),
    }
}

/// The person's Downloads folder, with a fallback for systems that do not define
/// one. An export must never fail because the folder is missing.
fn downloads_dir(app: &AppHandle) -> Result<PathBuf, String> {
    if let Ok(dir) = app.path().download_dir() {
        return Ok(dir);
    }
    let home = app.path().home_dir().map_err(|e| e.to_string())?;
    Ok(home.join("Downloads"))
}

fn vault_dir(app: &AppHandle, user: &str, project: &str) -> Result<PathBuf, String> {
    let base = app.path().app_data_dir().map_err(|e| e.to_string())?;
    let dir = base
        .join("vault")
        .join(checked_vault_segment(user, "account")?)
        .join(checked_vault_segment(project, "project")?);
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    gc_parts(&dir);
    Ok(dir)
}

fn document_path(
    app: &AppHandle,
    user: &str,
    project: &str,
    doc_id: &str,
    ext: &str,
    variant: &str,
) -> Result<PathBuf, String> {
    let dir = vault_dir(app, user, project)?;
    Ok(dir.join(file_name(doc_id, ext, variant)?))
}

/// Abandoned uploads are removed after a day; they are never a document.
fn gc_parts(dir: &Path) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    let cutoff = std::time::SystemTime::now()
        .checked_sub(std::time::Duration::from_secs(24 * 60 * 60));
    let Some(cutoff) = cutoff else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let is_part = path
            .file_name()
            .and_then(|name| name.to_str())
            .map(|name| name.ends_with(".part"))
            .unwrap_or(false);
        if !is_part {
            continue;
        }
        let stale = entry
            .metadata()
            .and_then(|meta| meta.modified())
            .map(|modified| modified < cutoff)
            .unwrap_or(false);
        if stale {
            let _ = fs::remove_file(path);
        }
    }
}

// ---------------------------------------------------------------------------
// Fingerprint + base64 (no extra crates)
// ---------------------------------------------------------------------------

fn fnv1a(mut hash: u64, bytes: &[u8]) -> u64 {
    for byte in bytes {
        hash ^= *byte as u64;
        hash = hash.wrapping_mul(0x100000001b3);
    }
    hash
}

const FNV_OFFSET: u64 = 0xcbf29ce484222325;

#[cfg(test)]
pub(crate) fn checksum_of(bytes: &[u8]) -> String {
    format!("{:016x}", fnv1a(FNV_OFFSET, bytes))
}

fn file_checksum(path: &Path) -> Result<(u64, String), String> {
    let mut file = fs::File::open(path).map_err(|e| e.to_string())?;
    let mut buffer = [0u8; 64 * 1024];
    let mut hash = FNV_OFFSET;
    let mut size = 0u64;
    loop {
        let read = file.read(&mut buffer).map_err(|e| e.to_string())?;
        if read == 0 {
            break;
        }
        hash = fnv1a(hash, &buffer[..read]);
        size += read as u64;
    }
    Ok((size, format!("{hash:016x}")))
}

const ALPHABET: &[u8; 64] =
    b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

pub(crate) fn encode_base64(bytes: &[u8]) -> String {
    let mut out = String::with_capacity((bytes.len() + 2) / 3 * 4);
    for chunk in bytes.chunks(3) {
        let b0 = chunk[0] as u32;
        let b1 = chunk.get(1).copied().unwrap_or(0) as u32;
        let b2 = chunk.get(2).copied().unwrap_or(0) as u32;
        let n = (b0 << 16) | (b1 << 8) | b2;
        out.push(ALPHABET[((n >> 18) & 63) as usize] as char);
        out.push(ALPHABET[((n >> 12) & 63) as usize] as char);
        if chunk.len() > 1 {
            out.push(ALPHABET[((n >> 6) & 63) as usize] as char);
        } else {
            out.push('=');
        }
        if chunk.len() > 2 {
            out.push(ALPHABET[(n & 63) as usize] as char);
        } else {
            out.push('=');
        }
    }
    out
}

pub(crate) fn decode_base64(input: &str) -> Result<Vec<u8>, String> {
    let mut out = Vec::with_capacity(input.len() * 3 / 4 + 3);
    let mut buffer: u32 = 0;
    let mut bits: u8 = 0;
    for byte in input.bytes() {
        if byte.is_ascii_whitespace() {
            continue;
        }
        if byte == b'=' {
            break;
        }
        let value = match byte {
            b'A'..=b'Z' => byte - b'A',
            b'a'..=b'z' => byte - b'a' + 26,
            b'0'..=b'9' => byte - b'0' + 52,
            b'+' => 62,
            b'/' => 63,
            _ => return Err("the uploaded data is not valid base64".into()),
        };
        buffer = (buffer << 6) | value as u32;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push(((buffer >> bits) & 0xff) as u8);
        }
    }
    Ok(out)
}

