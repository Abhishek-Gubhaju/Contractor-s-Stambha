// ============================================================================
// File Vault — real files on disk.
//
// The webview never stores a document in localStorage. A picked file is sent
// here in 4 MiB chunks, appended to a `.part` file, fingerprinted (FNV-1a 64),
// fsynced and atomically renamed into
//
//     <app data>/vault/<account>/<PROJECT>/<doc id>.<ext>
//
// Thumbnails live beside it as `<doc id>.thumb.jpg`. Nothing in this module
// trusts a path from the webview: ids, extensions and folder names are all
// re-validated, and every file resolves inside the account's project folder.
// Opening a file hands it to the OS default handler — never inside the webview.
// ============================================================================
use serde::Serialize;
use std::collections::HashMap;
use std::fs;
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use tauri::{AppHandle, Manager};

use crate::atomic_write;

/// A single file may not exceed this. Bigger than any drawing/scan we expect,
/// small enough that a mistake cannot fill the disk unnoticed.
pub const MAX_FILE_BYTES: u64 = 512 * 1024 * 1024;
/// Files larger than this are never pulled back into the webview for preview.
const MAX_INLINE_BYTES: u64 = 64 * 1024 * 1024;

/// Extensions we are willing to hand to the OS default application. Everything
/// else can still be stored, revealed and exported — but never executed.
const OPEN_EXTS: &[&str] = &[
    "pdf", "doc", "docx", "xls", "xlsx", "ppt", "pptx", "txt", "csv", "md", "rtf", "odt",
    "ods", "odp", "png", "jpg", "jpeg", "gif", "webp", "bmp", "tif", "tiff", "heic",
    "dwg", "dxf", "dwf", "zip", "rar", "7z", "mp4", "mov", "m4v", "mp3", "wav", "json", "xml",
    "log", "eml",
];

struct UploadState {
    ext: String,
    total_chunks: u32,
    total_bytes: u64,
    next_chunk: u32,
    written: u64,
    hash: u64,
    tmp: PathBuf,
}

static SESSIONS: Mutex<Option<HashMap<String, UploadState>>> = Mutex::new(None);

fn sessions() -> std::sync::MutexGuard<'static, Option<HashMap<String, UploadState>>> {
    let mut guard = SESSIONS.lock().unwrap_or_else(|error| error.into_inner());
    if guard.is_none() {
        *guard = Some(HashMap::new());
    }
    guard
}

