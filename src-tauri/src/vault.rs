pub struct VaultRestoreInfo {
    pub restored: u64,
    pub skipped: u64,
}

#[derive(Serialize)]
struct VaultManifestFile {
    name: String,
    bytes: u64,
    checksum: String,
}

#[derive(Serialize)]
struct VaultManifest {
    app: String,
    kind: String,
    files: Vec<VaultManifestFile>,
}

fn is_document_file(name: &str) -> bool {
    !name.ends_with(".part") && !name.contains(".thumb.") && name != "vault-manifest.json"
}

/// Copy this project's documents into a backup run folder. Thumbnails travel
/// too (they are cheap and make a restored vault usable immediately).
#[tauri::command]
pub fn vault_backup_copy(
    app: AppHandle,
    user: String,
    project: String,
    destination: String,
) -> Result<VaultCopyInfo, String> {
    let source = vault_dir(&app, &user, &project)?;
    let dest = PathBuf::from(&destination);
    if !dest.is_absolute() || destination.trim().is_empty() {
        return Err("refusing to write a vault copy outside an absolute folder".into());
    }
    fs::create_dir_all(&dest).map_err(|e| e.to_string())?;

    let mut files = Vec::new();
    let mut bytes = 0u64;
    for entry in fs::read_dir(&source)
        .map_err(|e| e.to_string())?
        .flatten()
    {
        let name = match entry.file_name().to_str() {
            Some(value) => value.to_string(),
            None => continue,
        };
        if name.ends_with(".part") || name == "vault-manifest.json" {
            continue;
        }
        let meta = entry.metadata().map_err(|e| e.to_string())?;
        if !meta.is_file() {
            continue;
        }
        let from = entry.path();
        let to = dest.join(&name);
        fs::copy(&from, &to).map_err(|e| e.to_string())?;
        bytes += meta.len();
        if is_document_file(&name) {
            let (_size, checksum) = file_checksum(&to)?;
            files.push(VaultManifestFile {
                name,
                bytes: meta.len(),
                checksum,
            });
        }
    }

    let manifest = VaultManifest {
        app: crate::APP_MARKER.into(),
        kind: "vault".into(),
        files,
    };
    let json = serde_json::to_vec_pretty(&manifest).map_err(|e| e.to_string())?;
    atomic_write(&dest.join("vault-manifest.json"), &json)?;
    Ok(VaultCopyInfo {
        files: manifest.files.len() as u64,
        bytes,
    })
}

/// Merge a run's `Vault/` folder back in. A file already present with the same
/// size and checksum is skipped; a different file is never overwritten.
#[tauri::command]
pub fn vault_restore_copy(
    app: AppHandle,
    user: String,
    project: String,
    source: String,
) -> Result<VaultRestoreInfo, String> {
    let src = PathBuf::from(&source);
    if !src.is_absolute() || source.trim().is_empty() {
        return Err("refusing to read a vault copy from a relative folder".into());
    }
    if !src.is_dir() {
        // A backup made before the vault existed simply has nothing to restore.
        return Ok(VaultRestoreInfo {
            restored: 0,
            skipped: 0,
        });
    }
    let dest = vault_dir(&app, &user, &project)?;
    let mut restored = 0u64;
    let mut skipped = 0u64;
    for entry in fs::read_dir(&src).map_err(|e| e.to_string())?.flatten() {
        let name = match entry.file_name().to_str() {
            Some(value) => value.to_string(),
            None => continue,
        };
        if name.ends_with(".part") || name == "vault-manifest.json" {
            continue;
        }
        if name.contains('/') || name.contains('\\') || name == "." || name == ".." {
            continue;
        }
        let meta = entry.metadata().map_err(|e| e.to_string())?;
        if !meta.is_file() {
            continue;
        }
        let target = dest.join(&name);
        if target.exists() {
            let same = match (file_checksum(&entry.path()), file_checksum(&target)) {
                (Ok((a_size, a_hash)), Ok((b_size, b_hash))) => {
                    a_size == b_size && a_hash == b_hash
                }
                _ => false,
            };
            if same {
                skipped += 1;
            } else {
                // Never replace something already on this machine.
                skipped += 1;
            }
            continue;
        }
        fs::copy(entry.path(), &target).map_err(|e| e.to_string())?;
        restored += 1;
    }
    Ok(VaultRestoreInfo { restored, skipped })
}

#[tauri::command]
pub fn vault_purge_user(app: AppHandle, user: String) -> Result<u64, String> {
    let base = app.path().app_data_dir().map_err(|e| e.to_string())?;
    let dir = base
        .join("vault")
        .join(checked_vault_segment(&user, "account")?);
    if !dir.exists() {
        return Ok(0);
    }
    let mut removed = 0u64;
    if let Ok(entries) = fs::read_dir(&dir) {
        for entry in entries.flatten() {
            if entry.file_type().map(|kind| kind.is_file()).unwrap_or(false) {
                removed += 1;
            }
        }
    }
    fs::remove_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(removed)
}

