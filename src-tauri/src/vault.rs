#[derive(Serialize)]
pub struct VaultWriteInfo {
    pub checksum: String,
    pub size_bytes: u64,
}

fn session_key(user: &str, project: &str, doc_id: &str, variant: &str) -> String {
    format!("{user}/{project}/{doc_id}/{variant}")
}

#[tauri::command]
pub fn vault_upload_begin(
    app: AppHandle,
    user: String,
    project: String,
    doc_id: String,
    ext: String,
    total_chunks: u32,
    total_bytes: u64,
    variant: String,
) -> Result<(), String> {
    if total_bytes == 0 {
        return Err("That file is empty — there is nothing to store.".into());
    }
    if total_bytes > MAX_FILE_BYTES {
        return Err(format!(
            "Files are limited to {} MB. Split or compress this one first.",
            MAX_FILE_BYTES / (1024 * 1024)
        ));
    }
    if total_chunks == 0 {
        return Err("That file could not be read.".into());
    }
    let dir = vault_dir(&app, &user, &project)?;
    checked_doc_id(&doc_id)?;
    let ext = checked_ext(&ext)?;
    variant_suffix(&variant)?;

    let tmp = dir.join(format!(
        "{}.{}.part",
        checked_doc_id(&doc_id)?,
        if variant == "thumb" { "thumb" } else { "file" }
    ));
    let _ = fs::remove_file(&tmp);
    fs::write(&tmp, b"").map_err(|e| e.to_string())?;

    let key = session_key(&user, &project, &doc_id, &variant);
    sessions().as_mut().unwrap().insert(
        key,
        UploadState {
            ext,
            total_chunks,
            total_bytes,
            next_chunk: 0,
            written: 0,
            hash: FNV_OFFSET,
            tmp,
        },
    );
    Ok(())
}

#[tauri::command]
pub fn vault_upload_chunk(
    _app: AppHandle,
    user: String,
    project: String,
    doc_id: String,
    chunk_index: u32,
    data_base64: String,
    variant: String,
) -> Result<(), String> {
    let bytes = decode_base64(&data_base64)?;
    let key = session_key(&user, &project, &doc_id, &variant);
    let mut guard = sessions();
    let state = guard
        .as_mut()
        .unwrap()
        .get_mut(&key)
        .ok_or_else(|| "That upload is no longer active — start it again.".to_string())?;
    if chunk_index != state.next_chunk {
        return Err("The upload arrived out of order — start it again.".into());
    }
    if state.written + bytes.len() as u64 > state.total_bytes {
        return Err("That upload is larger than the file it declared.".into());
    }
    let mut file = fs::OpenOptions::new()
        .append(true)
        .open(&state.tmp)
        .map_err(|e| e.to_string())?;
    file.write_all(&bytes).map_err(|e| e.to_string())?;
    state.hash = fnv1a(state.hash, &bytes);
    state.written += bytes.len() as u64;
    state.next_chunk += 1;
    Ok(())
}

#[tauri::command]
pub fn vault_upload_finish(
    _app: AppHandle,
    user: String,
    project: String,
    doc_id: String,
    checksum: Option<String>,
    variant: String,
) -> Result<VaultWriteInfo, String> {
    let key = session_key(&user, &project, &doc_id, &variant);
    let state = {
        let mut guard = sessions();
        let state = guard
            .as_mut()
            .unwrap()
            .remove(&key)
            .ok_or_else(|| "That upload is no longer active — start it again.".to_string())?;
        state
    };

    let fail = |message: String| -> Result<VaultWriteInfo, String> {
        let _ = fs::remove_file(&state.tmp);
        Err(message)
    };
    if state.next_chunk != state.total_chunks || state.written != state.total_bytes {
        return fail("The upload did not finish — the file is incomplete.".into());
    }
    let computed = format!("{:016x}", state.hash);
    if let Some(expected) = checksum {
        if !expected.is_empty() && expected != computed {
            return fail("The file changed while it was being saved. Try again.".into());
        }
    }
    if let Ok(file) = fs::OpenOptions::new().write(true).open(&state.tmp) {
        let _ = file.sync_all();
    }
    let name = file_name(&doc_id, &state.ext, &variant)?;
    let target = state.tmp.with_file_name(name);
    if target.exists() {
        let _ = fs::remove_file(&target);
    }
    fs::rename(&state.tmp, &target).map_err(|e| e.to_string())?;
    Ok(VaultWriteInfo {
        checksum: computed,
        size_bytes: state.written,
    })
}

#[tauri::command]
pub fn vault_upload_abort(
    _app: AppHandle,
    user: String,
    project: String,
    doc_id: String,
    variant: String,
) -> Result<(), String> {
    let key = session_key(&user, &project, &doc_id, &variant);
    let state = sessions().as_mut().unwrap().remove(&key);
    if let Some(state) = state {
        let _ = fs::remove_file(&state.tmp);
    }
    Ok(())
}

